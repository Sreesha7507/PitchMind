@app.post("/upload-readme")
async def upload_readme(file: UploadFile = File(...)):
    raw = await file.read()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("latin-1")
    return {"content": text, "filename": file.filename}


@app.post("/generate")
async def generate_pitch(req: GenerateRequest):
    """
    Core endpoint — full Hindsight + Groq flow:
      1. Recall memories for this session
      2. Generate pitch with Groq (memories injected as context)
      3. Store new memories (doc summary, company name, feedback, prefs)
      4. Return deck + metadata about memories used
    """
    if not req.documentation or len(req.documentation.strip()) < 50:
        raise HTTPException(400, "Documentation too short — please provide more context.")

    session_id = req.session_id or f"pm-{uuid.uuid4().hex[:10]}"
    bank_id    = session_id

    # ── 1. Retrieve memories ────────────────────────────────────────────────
    proj_mems = await hs_recall(bank_id, "project details, product, market, business model, company")
    pref_mems = await hs_recall(bank_id, "user preferences, feedback, slide style, tone, improvements")
    all_mems  = proj_mems + pref_mems

    mems_ctx  = "\n".join(f"• {m['text']}" for m in proj_mems)
    prefs_ctx = "\n".join(f"• {m['text']}" for m in pref_mems)

    # ── 2. Generate pitch ───────────────────────────────────────────────────
    try:
        deck = generate_with_groq(req.documentation, mems_ctx, prefs_ctx)
    except json.JSONDecodeError as exc:
        raise HTTPException(500, f"LLM returned invalid JSON — try again. Detail: {exc}")
    except Exception as exc:
        raise HTTPException(500, f"Groq error: {exc}")

    # ── 3. Store memories ───────────────────────────────────────────────────
    await hs_retain(bank_id,
              f"Project documentation (first 800 chars): {req.documentation[:800]}",
              context="readme upload")

    try:
        company = deck["slides"][0]["title"]
        tagline = deck["slides"][0].get("subtitle") or ""
        await hs_retain(bank_id,
                  f"Company: {company}. Tagline: {tagline}",
                  context="pitch generation")
    except Exception:
        pass

    if req.feedback:
        await hs_retain(bank_id,
                  f"User feedback on previous pitch: {req.feedback}",
                  context="user feedback")
    if req.preferences:
        await hs_retain(bank_id,
                  f"User style preferences: {req.preferences}",
                  context="user preferences")

    # ── 4. Return ───────────────────────────────────────────────────────────
    return {
        "session_id":      session_id,
        "deck":            deck,
        "memories_used":   [{"text": m["text"], "type": m["type"]} for m in all_mems],
        "memories_count":  len(all_mems),
        "is_improved":     len(all_mems) > 0,
        "hindsight_active": HINDSIGHT_AVAILABLE,
    }


@app.post("/regenerate")
async def regenerate_pitch(req: GenerateRequest):
    """Alias of /generate — regenerates using updated memories."""
    return await generate_pitch(req)


@app.post("/feedback")
async def save_feedback(req: FeedbackRequest):
    ctx   = f"slide {req.slide_number}" if req.slide_number else "general feedback"
    saved = await hs_retain(req.session_id,
                            f"User feedback ({ctx}): {req.feedback}",
                            context="user feedback")
    return {"saved": saved, "session_id": req.session_id}


@app.get("/memories/{session_id}")
async def get_memories(session_id: str):
    mems = await hs_list(session_id)
    return {"session_id": session_id, "memories": mems, "count": len(mems)}
