# ── Hindsight helpers (async — required inside FastAPI's event loop) ───────────
#
# The hindsight-client sync wrappers (retain, recall, list_memories) call
# asyncio.get_event_loop().run_until_complete() internally.  When invoked from
# inside FastAPI's already-running event loop they raise:
#   RuntimeError: This event loop is already running
# which the bare except catches and discards silently.
# Fix: use the async a* variants (aretain, arecall, alist_memories, acreate_bank).

async def _ensure_bank(bank_id: str) -> None:
    """Create bank if it doesn't exist; silently swallow 'already exists' errors."""
    if not HINDSIGHT_AVAILABLE:
        return
    try:
        await hindsight_client.acreate_bank(
            bank_id=bank_id,
            retain_mission=(
                "You are a pitch deck memory assistant. "
                "Remember project details, the user's stylistic preferences, "
                "and any feedback given on previous pitch decks."
            ),
        )
    except Exception:
        pass  # bank already exists — that's fine


async def hs_retain(bank_id: str, content: str, context: str = "") -> bool:
    if not HINDSIGHT_AVAILABLE:
        return False
    try:
        await _ensure_bank(bank_id)
        await hindsight_client.aretain(bank_id=bank_id, content=content, context=context)
        return True
    except Exception as exc:
        print(f"[Hindsight] retain error: {exc}")
        return False


async def hs_recall(bank_id: str, query: str) -> list[dict]:
    if not HINDSIGHT_AVAILABLE:
        return []
    try:
        result = await hindsight_client.arecall(bank_id=bank_id, query=query, budget="mid")
        return [
            {"text": m.text, "type": getattr(m, "type", "observation")}
            for m in result.results
        ]
    except Exception as exc:
        print(f"[Hindsight] recall error: {exc}")
        return []


async def hs_list(bank_id: str) -> list[dict]:
    if not HINDSIGHT_AVAILABLE:
        return []
    try:
        result = await hindsight_client.alist_memories(bank_id=bank_id, limit=50)
        memories = []
        for m in result.items:
            text = m.text if hasattr(m, "text") else str(m)
            memories.append({"text": text, "type": getattr(m, "type", "observation")})
        return memories
    except Exception as exc:
        print(f"[Hindsight] list error: {exc}")
        return []

# ── Groq slide generation ─────────────────────────────────────────────────────

SYSTEM_PROMPT = """\
You are a world-class startup pitch deck writer who has helped founders raise over $500 M.
You produce clear, compelling, data-driven slides.

Generate exactly 8 slides for an investor pitch deck as **valid JSON only**.
Each slide object must contain:
  - slide_number   : integer 1–8
  - title          : short punchy heading
  - subtitle       : one-line supporting headline (string or null)
  - bullet_points  : array of 3–5 crisp strings
  - key_metric     : one standout stat/number (string or null)
  - speaker_notes  : 2–3 sentences the founder would say aloud

Slide order:
  1. Cover          — company name, tagline
  2. Problem        — pain point, market gap
  3. Solution       — what you built
  4. Product        — mechanics, tech, demo flow
  5. Market         — TAM, target customer
  6. Competitive Advantage — moat, differentiation
  7. Business Model — revenue streams, pricing
  8. Roadmap        — milestones, funding ask

Return ONLY a JSON object with a single key "slides" whose value is an array of 8 slide objects.
Do NOT wrap in markdown fences. Do NOT add any text outside the JSON.\
"""


def _strip_fences(raw: str) -> str:
    """Remove accidental ```json … ``` wrappers from LLM output."""
    raw = raw.strip()
    if raw.startswith("```"):
        parts = raw.split("```")
        # parts[1] is the content inside the fence (may start with "json\n")
        raw = parts[1]
        if raw.lower().startswith("json"):
            raw = raw[4:]
    return raw.strip()


def generate_with_groq(
    documentation: str,
    memories_ctx: str = "",
    prefs_ctx: str = "",
) -> dict:
    memory_block = ""
    if memories_ctx or prefs_ctx:
        memory_block = (
            "\n## Context from Hindsight Memory (previous sessions)\n"
            f"{memories_ctx}\n\n"
            "## Remembered User Preferences\n"
            f"{prefs_ctx}\n\n"
            "Use the above to personalise and improve this pitch compared to any previous version.\n"
        )

    user_msg = f"{memory_block}\n## Documentation\n\n{documentation}\n\nGenerate the pitch deck JSON now."

    response = groq_client.chat.completions.create(
        model="openai/gpt-oss-120b",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": user_msg},
        ],
        temperature=0.7,
        max_tokens=4096,
    )

    raw = response.choices[0].message.content
    cleaned = _strip_fences(raw)
    return json.loads(cleaned)

